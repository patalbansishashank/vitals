import { open, BASE, shot, text, dump } from './lib.mjs';
const mobile = process.argv[2] === 'mobile';
const { browser, page, errors } = await open({ mobile, profile: 'p1' });
const T = async (n = 2000) => (await text(page, 9000)).replace(/\n+/g, ' / ').slice(0, n);
await page.goto(BASE + '/coach', { waitUntil: 'networkidle' }); await page.waitForTimeout(2500);
console.log('COACH0', await T(1200));
const box = page.locator('textarea, input[type=text]').last();
await box.fill('had dal and rice for lunch'); await page.keyboard.press('Enter');
await page.getByText(/Undo/).first().waitFor({ timeout: 30000 }).catch(() => console.log('no Undo seen'));
await page.waitForTimeout(2500);
console.log('COACH1', await T(2200)); await shot(page, mobile ? '31-coach-card-m' : '30-coach-card');
await page.reload({ waitUntil: 'networkidle' }); await page.waitForTimeout(3000);
console.log('COACH2 reload', await T(2200)); await shot(page, mobile ? '32-coach-reload-m' : '31-coach-reload');
await page.getByRole('button', { name: /Undo/ }).first().click(); await page.waitForTimeout(2500);
console.log('COACH3 undone', await T(2200)); await shot(page, mobile ? '33-coach-undone-m' : '32-coach-undone');
await page.goto(BASE + '/today', { waitUntil: 'networkidle' }); await page.waitForTimeout(2500);
console.log('TODAY', (await text(page, 2500)).replace(/\n+/g, ' / ').slice(0, 1100));
console.log('ERRORS', errors);
