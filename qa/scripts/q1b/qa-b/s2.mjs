import { open, BASE, shot, text, dump } from './lib.mjs';
const mobile = process.argv[2] === 'mobile';
const { browser, page, errors } = await open({ mobile, profile: process.argv[3] || 'p5' });
const T = async (n = 2000) => (await text(page, 9000)).replace(/\n+/g, ' / ').slice(0, n);
await page.goto(BASE + '/simulate/starter/schedule', { waitUntil: 'networkidle' }); await page.waitForTimeout(2500);
await page.getByRole('button', { name: 'Run', exact: true }).click();
await page.waitForTimeout(8000);
console.log('URL', page.url());
console.log('RESULTS', await T(1800));
await dump(page, 'results'); await shot(page, mobile ? '41-sim-results-m' : '41-sim-results');
const start = page.getByRole('button', { name: /Start this plan|Replace active plan/ }); console.log('start btns', await start.count());
await start.first().click(); await page.waitForTimeout(2000);
await page.getByRole('button', { name: 'today', exact: true }).last().click().catch(e => console.log('today fail')); await page.waitForTimeout(500);
await page.getByRole('button', { name: 'Replace active plan…' }).last().click(); await page.waitForTimeout(1500);
const ad = page.getByRole('alertdialog'); console.log('ALERT', (await ad.innerText()).replace(/\n+/g, ' / ')); await shot(page, mobile ? '43-sim-replace-m' : '43-sim-replace');
const inp = ad.locator('input'); const m = (await ad.innerText()).match(/type\s+[“"']?([A-Za-z]+)[”"']?/i); console.log('word', m && m[1], 'inputs', await inp.count());
if (await inp.count()) await inp.first().fill(m ? m[1] : 'replace'); await page.waitForTimeout(500);
const btns = await ad.getByRole('button').evaluateAll(b => b.map(x => x.innerText + (x.getAttribute('aria-disabled') ? '(dis)' : ''))); console.log('btns', btns);
await ad.getByRole('button').last().click(); await page.waitForTimeout(4000);
console.log('URL AFTER', page.url());
await page.goto(BASE + '/today', { waitUntil: 'networkidle' }); await page.waitForTimeout(3000);
console.log('TODAY', await T(1200)); await shot(page, mobile ? '44-today-custom-m' : '44-today-custom');
await page.goto(BASE + '/plan/active', { waitUntil: 'networkidle' }); await page.waitForTimeout(2500);
console.log('PLAN', await T(1500));
console.log('ERRORS', errors);
await browser.close();
