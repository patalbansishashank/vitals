#!/usr/bin/env node
/**
 * Generates `src/content/catalogues/kitchen.ts` from the R12 seed (`research/R12-seed.json`): equipment,
 * cuisines, staples, pantry and regions, one item per line. `src/content/catalogues/__tests__/kitchen.test.ts` checks
 * that the module equals the seed.
 *
 *   node scripts/kitchen-catalogue.mjs            # write
 *   node scripts/kitchen-catalogue.mjs --check    # exit 1 when the module is out of date
 */
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..');
export const SEED_PATH = join(ROOT, 'research', 'R12-seed.json');
export const OUT_PATH = join(ROOT, 'src', 'content', 'catalogues', 'kitchen.ts');
const LISTS = ['equipment', 'cuisines', 'staples', 'pantry', 'regions'];

export function render(seed) {
  const out = [
    '/**',
    ' * GENERATED by `scripts/kitchen-catalogue.mjs` from the R12 seed. Do not edit by hand: change the seed and run',
    ' * `node scripts/kitchen-catalogue.mjs`. Kitchen equipment, cuisines, staples, pantry items and regional defaults',
    ' * (counts in `KITCHEN_COUNTS`). Food links: `foodRef.usdaFdcId` (USDA SR Legacy), `fixtureId` (test fixture only),',
    ' * `ifctPending` (the best source is IFCT 2017, not yet licensed: never shown as a nutrient claim).',
    ' */',
    "import type { KitchenSeed } from '@/catalogues/kitchen/types';",
    '',
    'export const KITCHEN_SEED: KitchenSeed = {',
    `  version: ${JSON.stringify(seed.version)},`,
    `  generated: ${JSON.stringify(seed.generated)},`,
    `  notes: ${JSON.stringify(seed.notes)},`,
  ];
  for (const k of LISTS) {
    out.push(`  ${k}: [`);
    for (const item of seed[k]) out.push(`    ${JSON.stringify(item)},`);
    out.push('  ],');
  }
  out.push('};', '');
  const counts = Object.fromEntries(LISTS.map((k) => [k, seed[k].length]));
  out.push(`export const KITCHEN_COUNTS = ${JSON.stringify(counts)} as const;`, '');
  return out.join('\n');
}

if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]) {
  const seed = JSON.parse(readFileSync(SEED_PATH, 'utf8'));
  const text = render(seed);
  if (process.argv.includes('--check')) {
    const now = readFileSync(OUT_PATH, 'utf8');
    if (now !== text) {
      console.error('src/content/catalogues/kitchen.ts is out of date: run node scripts/kitchen-catalogue.mjs');
      process.exit(1);
    }
  } else {
    writeFileSync(OUT_PATH, text);
    console.log(`wrote ${OUT_PATH}`, Object.fromEntries(LISTS.map((k) => [k, seed[k].length])));
  }
}
