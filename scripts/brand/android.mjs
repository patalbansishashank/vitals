/** Writes the res folder, the Play Store icon, the previews and the README. Returns the written paths. */
export async function writeAndroid() {
  const res = androidResources();
  const written = [];
  const put = async (file, data) => {
    await mkdir(path.dirname(file), { recursive: true });
    await writeFile(file, data);
    written.push(file);
  };
  for (const [rel, xml] of Object.entries(res)) await put(path.join(RES_DIR, rel), xml);

  const colourMap = readColours(res['values/vitals_brand_colors.xml']);
  const bg = res['drawable/vitals_launcher_background.xml'];
  const fg = res['drawable/vitals_launcher_foreground.xml'];
  await put(path.join(OUT_DIR, 'playstore-512.png'), await rasterise(launcherSvg(bg, fg, colourMap, null), 512));
  for (const mask of Object.keys(LAUNCHER_MASKS)) {
    await put(path.join(OUT_DIR, 'preview', `launcher-${mask}.png`), await rasterise(launcherSvg(bg, fg, colourMap, mask), 432));
  }
  await put(path.join(OUT_DIR, 'README.md'), README);
  return written;
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const written = await writeAndroid();
  console.log(`${written.length} Android brand files written to`, path.relative(ROOT, OUT_DIR));
}
