// A tiny XML reader and a vector-drawable → SVG converter, for the previews and the tests (no Android tooling here).

/**
 * @typedef {{ name: string, attrs: Record<string, string>, children: XmlNode[], text: string }} XmlNode
 */

/** Parses the subset of XML these resources use (declaration, comments, elements, attributes). Throws if malformed. */
export function parseXml(src) {
  const re = /<\?[\s\S]*?\?>|<!--[\s\S]*?-->|<\/([\w:.-]+)\s*>|<([\w:.-]+)((?:\s+[\w:.-]+\s*=\s*"[^"<]*")*)\s*(\/?)>|([^<]+)|(<)/g;
  /** @type {XmlNode} */
  const doc = { name: '#document', attrs: {}, children: [], text: '' };
  const stack = [doc];
  for (const t of src.matchAll(re)) {
    const [, close, open, attrSrc, selfClose, text, stray] = t;
    if (stray) throw new Error(`malformed XML near offset ${t.index}`);
    if (text !== undefined) {
      if (/&(?!(amp|lt|gt|quot|apos|#\d+);)/.test(text)) throw new Error(`stray & in "${text.trim().slice(0, 20)}"`);
      if (stack.length === 1 && text.trim()) throw new Error('text outside the root element');
      stack.at(-1).text += text.trim();
      continue;
    }
    if (close) {
      const top = stack.pop();
      if (!top || top.name !== close) throw new Error(`</${close}> closes <${top?.name}>`);
      continue;
    }
    if (!open) continue;
    /** @type {Record<string, string>} */
    const attrs = {};
    for (const [, k, v] of (attrSrc ?? '').matchAll(/([\w:.-]+)\s*=\s*"([^"]*)"/g)) {
      if (k in attrs) throw new Error(`duplicate attribute ${k}`);
      attrs[k] = v;
    }
    const node = { name: open, attrs, children: [], text: '' };
    stack.at(-1).children.push(node);
    if (!selfClose) stack.push(node);
  }
  if (stack.length !== 1) throw new Error(`unclosed <${stack.at(-1).name}>`);
  if (doc.children.length !== 1) throw new Error('expected one root element');
  return doc.children[0];
}

/** name → colour from a values XML. */
export function readColours(xml) {
  return Object.fromEntries(
    parseXml(xml)
      .children.filter((n) => n.name === 'color')
      .map((n) => [n.attrs.name, n.text]),
  );
}

/** Android colour (#RGB, #RRGGBB, #AARRGGBB, @color/x, @android:color/white|black|transparent) → SVG paint + opacity. */
function paint(value, colourMap) {
  if (!value) return null;
  let v = value;
  if (v.startsWith('@color/')) {
    v = colourMap[v.slice(7)];
    if (!v) throw new Error(`unknown colour ${value}`);
  }
  v = { '@android:color/white': '#ffffff', '@android:color/black': '#000000', '@android:color/transparent': '#00000000' }[v] ?? v;
  const hex = v.replace('#', '');
  if (hex.length === 8) {
    const alpha = parseInt(hex.slice(0, 2), 16) / 255;
    return alpha === 0 ? null : { colour: `#${hex.slice(2)}`, alpha };
  }
  if (hex.length === 6 || hex.length === 3) return { colour: `#${hex}`, alpha: 1 };
  throw new Error(`unsupported colour ${value}`);
}

const A = (n, k) => n.attrs[`android:${k}`];
const num = (n, k, d) => (A(n, k) === undefined ? d : Number(A(n, k)));

/** Android's group matrix: translate(-pivot), scale, rotate, translate(translate + pivot). */
const groupTransform = (g) => {
  const [px, py] = [num(g, 'pivotX', 0), num(g, 'pivotY', 0)];
  return (
    `translate(${num(g, 'translateX', 0) + px} ${num(g, 'translateY', 0) + py}) rotate(${num(g, 'rotation', 0)}) ` +
    `scale(${num(g, 'scaleX', 1)} ${num(g, 'scaleY', 1)}) translate(${-px} ${-py})`
  );
};

/** SVG elements (no <svg> wrapper) for a vector drawable's contents in its viewport coordinates. */
export function vectorBody(xml, colourMap = {}) {
  const root = parseXml(xml);
  if (root.name !== 'vector') throw new Error(`expected <vector>, got <${root.name}>`);
  const walk = (n) => {
    if (n.name === 'group') return `<g transform="${groupTransform(n)}">${n.children.map(walk).join('')}</g>`;
    if (n.name !== 'path') throw new Error(`unsupported element <${n.name}>`);
    const fill = paint(A(n, 'fillColor'), colourMap);
    const stroke = paint(A(n, 'strokeColor'), colourMap);
    const attrs = [`d="${A(n, 'pathData')}"`, `fill="${fill ? fill.colour : 'none'}"`];
    if (fill && fill.alpha * num(n, 'fillAlpha', 1) < 1) attrs.push(`fill-opacity="${fill.alpha * num(n, 'fillAlpha', 1)}"`);
    if (A(n, 'fillType') === 'evenOdd') attrs.push('fill-rule="evenodd"');
    if (stroke && num(n, 'strokeWidth', 0) > 0) {
      attrs.push(`stroke="${stroke.colour}"`, `stroke-width="${num(n, 'strokeWidth', 0)}"`);
      if (stroke.alpha * num(n, 'strokeAlpha', 1) < 1) attrs.push(`stroke-opacity="${stroke.alpha * num(n, 'strokeAlpha', 1)}"`);
      attrs.push(`stroke-linecap="${A(n, 'strokeLineCap') ?? 'butt'}"`, `stroke-linejoin="${A(n, 'strokeLineJoin') ?? 'miter'}"`);
    }
    return `<path ${attrs.join(' ')}/>`;
  };
  return { width: num(root, 'viewportWidth', GRID), height: num(root, 'viewportHeight', GRID), body: root.children.map(walk).join('') };
}

/** A vector drawable as a standalone SVG string (same viewport). */
export function vectorToSvg(xml, colourMap = {}) {
  const { width, height, body } = vectorBody(xml, colourMap);
  return `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 ${width} ${height}">${body}</svg>`;
}

/** Common launcher masks (AOSP shape paths on a 100 box), applied to the visible 72 dp of the 108 dp layers. */
export const LAUNCHER_MASKS = {
  circle: 'M50,0 A50,50 0,1 1,50,100 A50,50 0,1 1,50,0 Z',
  squircle: 'M50,0 C10,0 0,10 0,50 C0,90 10,100 50,100 C90,100 100,90 100,50 C100,10 90,0 50,0 Z',
  'rounded-square':
    'M50,0 L92,0 C96.42,0 100,3.58 100,8 L100,92 C100,96.42 96.42,100 92,100 L8,100 C3.58,100 0,96.42 0,92 L0,8 C0,3.58 3.58,0 8,0 Z',
  teardrop: 'M50,0 A50,50 0,0 1 100,50 L100,85 A15,15 0,0 1 85,100 L50,100 A50,50 0,0 1 0,50 A50,50 0,0 1 50,0 Z',
};
/** The visible part of the adaptive layers: the centre 72 of 108 dp. */
const VISIBLE = 72;
const INSET = (GRID - VISIBLE) / 2;
const maskTransform = `translate(${INSET} ${INSET}) scale(${VISIBLE / 100})`;

/** A launcher mask on the 108 grid, filled black on transparent (for rasterising and comparing alpha). */
export const maskSvg = (name) =>
  `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 ${GRID} ${GRID}"><path transform="${maskTransform}" d="${LAUNCHER_MASKS[name]}"/></svg>`;

/** Background + foreground through a mask, cropped to the visible 72 dp (or unmasked, full square, when mask is null). */
export function launcherSvg(backgroundXml, foregroundXml, colourMap, mask) {
  const bg = vectorBody(backgroundXml, colourMap).body;
  const fg = vectorBody(foregroundXml, colourMap).body;
  const clip = mask ? `<clipPath id="m"><path transform="${maskTransform}" d="${LAUNCHER_MASKS[mask]}"/></clipPath>` : '';
  return (
    `<svg xmlns="http://www.w3.org/2000/svg" viewBox="${INSET} ${INSET} ${VISIBLE} ${VISIBLE}">${clip}` +
    `<g${mask ? ' clip-path="url(#m)"' : ''}>${bg}${fg}</g></svg>`
  );
}

/** Rasterises an SVG string to a size × size PNG buffer (librsvg through sharp). */
export const rasterise = (svg, size) => {
  const box = Number(svg.match(/viewBox="[\d.-]+ [\d.-]+ ([\d.]+)/)?.[1] ?? GRID);
  return sharp(Buffer.from(svg), { density: (72 * size) / box }).resize(size, size).png({ compressionLevel: 9 }).toBuffer();
};

