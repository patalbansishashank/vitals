// Android brand resources for the Vitals app (Capacitor shell, minSdk 26). Run: node scripts/brand/android.mjs
// Every XML is built from the mark source (mark.mjs: readMark, PALETTE), so a change to public/brand/mark.svg or
// mark-small.svg flows through. Writes apps/android/brand/res/** (an Android res folder L-ANDROID copies or
// references), the Play Store icon and launcher-mask previews. apps/android/brand/README.md says how to wire them.
//
//   values(-night)/vitals_brand_colors.xml   launcher background (light in both modes), ink, signal, edge, splash ground
//   adaptive icon                            foreground + background + monochrome, mark inside the 66 dp safe circle
//   animated splash (Android 12+)            ring draws on (trim 0.05 → 1, 500 ms), then the dot pops in; ends by 640 ms
//   ic_stat_vitals                           white notification glyph from the small cut, inside the 20 dp live area
import { mkdir, writeFile } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';
import path from 'node:path';
import sharp from 'sharp';
import { GRID, PALETTE, ROOT, readMark } from './mark.mjs';

export const OUT_DIR = path.join(ROOT, 'apps', 'android', 'brand');
export const RES_DIR = path.join(OUT_DIR, 'res');

/** Adaptive icon: the mark's outer radius (33.5) × 0.76 ≈ 25.5 dp, well inside the 33 dp safe radius. Same as Lumen's mono. */
export const LAUNCHER_SCALE = 0.76;
/** Splash: 33.5 × 0.8 = 26.8 of the 36 viewport units that the 192 dp circle covers on the 288 dp icon. */
export const SPLASH_SCALE = 0.8;
/** Notification glyph (small cut, outer radius 35) × 1.2 = 42 of 108 units ≈ 9.3 dp, inside the 10 dp half live area. */
export const STAT_SCALE = 1.2;

export const SPLASH = { ringMs: 500, dotOffsetMs: 420, dotMs: 220, totalMs: 700, overshootTension: 1.2 };

const C = GRID / 2;
const NS = 'xmlns:android="http://schemas.android.com/apk/res/android"';
const HEAD = '<?xml version="1.0" encoding="utf-8"?>\n';
const fmt = (n) => String(Number(n.toFixed(3)));

/** A circle as path data (two arcs): Android vectors have no <circle>. */
export const circlePath = ({ cx, cy, r }) =>
  `M${fmt(cx - r)},${fmt(cy)} A${fmt(r)},${fmt(r)} 0,1 1,${fmt(cx + r)},${fmt(cy)} A${fmt(r)},${fmt(r)} 0,1 1,${fmt(cx - r)},${fmt(cy)} Z`;

const scaleGroup = (scale, body, name = '') =>
  `    <group${name ? ` android:name="${name}"` : ''} android:pivotX="${C}" android:pivotY="${C}" android:scaleX="${scale}" android:scaleY="${scale}">\n${body}    </group>\n`;

const vector = (dp, body) =>
  `${HEAD}<vector ${NS}\n    android:width="${dp}dp" android:height="${dp}dp" android:viewportWidth="${GRID}" android:viewportHeight="${GRID}">\n${body}</vector>\n`;

const ringPath = (m, stroke, name = '') =>
  `        <path${name ? ` android:name="${name}"` : ''} android:fillColor="@android:color/transparent" android:strokeColor="${stroke}"\n` +
  `            android:strokeWidth="${m.stroke}" android:strokeLineCap="round" android:strokeLineJoin="round"\n` +
  `            android:pathData="${m.d}" />\n`;

const dotPath = (m, fill, edge, indent = '        ') =>
  `${indent}<path android:fillColor="${fill}"${edge ? ` android:strokeColor="${edge}" android:strokeWidth="${m.dot.edge}"` : ''}\n` +
  `${indent}    android:pathData="${circlePath(m.dot)}" />\n`;

/** Android colour value for a palette entry; null (no edge) becomes fully transparent. */
const androidColour = (hex) => (hex ?? '#00000000');

const colours = (tone) => {
  const p = PALETTE[tone];
  const rows = [
    ['vitals_launcher_background', PALETTE.light.ground, 'launcher icon ground: light in both modes'],
    ['vitals_mark_ink', p.ink, 'the ring'],
    ['vitals_mark_signal', p.signal, 'the dot'],
    ['vitals_mark_edge', androidColour(p.edge), 'thin edge round the dot (light grounds only)'],
    ['vitals_splash_background', p.ground, 'splash ground'],
  ];
  return (
    `${HEAD}<!-- Generated by scripts/brand/android.mjs from scripts/brand/mark.mjs (PALETTE.${tone}). Do not edit. -->\n<resources>\n` +
    rows.map(([name, hex, note]) => `    <!-- ${note} -->\n    <color name="${name}">${hex}</color>\n`).join('') +
    '</resources>\n'
  );
};

/** The resources, keyed by path under res/. */
export function androidResources() {
  const m = readMark('mark.svg');
  const small = readMark('mark-small.svg');
  const light = PALETTE.light;
  const dotPivot = `android:pivotX="${m.dot.cx}" android:pivotY="${m.dot.cy}"`;

  return {
    'values/vitals_brand_colors.xml': colours('light'),
    'values-night/vitals_brand_colors.xml': colours('dark'),

    // Fixed colours: the launcher background is light in both modes, so the foreground never follows night mode.
    'drawable/vitals_launcher_foreground.xml': vector(
      108,
      scaleGroup(LAUNCHER_SCALE, ringPath(m, light.ink) + dotPath(m, light.signal, light.edge)),
    ),
    'drawable/vitals_launcher_background.xml': vector(
      108,
      `    <path android:fillColor="@color/vitals_launcher_background" android:pathData="M0,0 H${GRID} V${GRID} H0 Z" />\n`,
    ),
    // Themed icons (Android 13+): the launcher tints this; only white, the dot filled, no edge.
    'drawable/vitals_launcher_monochrome.xml': vector(
      108,
      scaleGroup(LAUNCHER_SCALE, ringPath(m, '#ffffff') + dotPath(m, '#ffffff', null)),
    ),
    ...Object.fromEntries(
      ['ic_launcher', 'ic_launcher_round'].map((name) => [
        `mipmap-anydpi-v26/${name}.xml`,
        `${HEAD}<adaptive-icon ${NS}>\n` +
          '    <background android:drawable="@drawable/vitals_launcher_background" />\n' +
          '    <foreground android:drawable="@drawable/vitals_launcher_foreground" />\n' +
          '    <monochrome android:drawable="@drawable/vitals_launcher_monochrome" />\n' +
          '</adaptive-icon>\n',
      ]),
    ),

    // Splash icon (no icon background): 288 dp, the content must fit the centre 192 dp circle.
    'drawable/vitals_splash_mark.xml': vector(
      288,
      scaleGroup(
        SPLASH_SCALE,
        ringPath(m, '@color/vitals_mark_ink', 'ring') +
          `        <group android:name="dot" ${dotPivot} android:scaleX="0" android:scaleY="0">\n` +
          dotPath(m, '@color/vitals_mark_signal', '@color/vitals_mark_edge', '            ') +
          '        </group>\n',
        'mark',
      ),
    ),
    'animator/vitals_splash_ring_draw.xml':
      `${HEAD}<objectAnimator ${NS}\n    android:propertyName="trimPathEnd" android:valueFrom="0.05" android:valueTo="1" android:valueType="floatType"\n` +
      `    android:duration="${SPLASH.ringMs}" android:interpolator="@android:interpolator/fast_out_slow_in" />\n`,
    'animator/vitals_splash_dot_pop.xml':
      `${HEAD}<set ${NS} android:ordering="together">\n` +
      ['scaleX', 'scaleY']
        .map(
          (prop) =>
            `    <objectAnimator android:propertyName="${prop}" android:valueFrom="0" android:valueTo="1" android:valueType="floatType"\n` +
            `        android:startOffset="${SPLASH.dotOffsetMs}" android:duration="${SPLASH.dotMs}" android:interpolator="@interpolator/vitals_splash_overshoot" />\n`,
        )
        .join('') +
      '</set>\n',
    // A small overshoot: the dot settles rather than bounces (the framework's overshoot uses tension 2).
    'interpolator/vitals_splash_overshoot.xml': `${HEAD}<overshootInterpolator ${NS} android:tension="${SPLASH.overshootTension}" />\n`,
    'drawable/vitals_splash_animated.xml':
      `${HEAD}<animated-vector ${NS}\n    android:drawable="@drawable/vitals_splash_mark">\n` +
      '    <target android:name="ring" android:animation="@animator/vitals_splash_ring_draw" />\n' +
      '    <target android:name="dot" android:animation="@animator/vitals_splash_dot_pop" />\n' +
      '</animated-vector>\n',

    // Status bar icon: Android tints it, so white only; the small cut stays open at 24 dp.
    'drawable/ic_stat_vitals.xml': vector(24, scaleGroup(STAT_SCALE, ringPath(small, '#ffffff') + dotPath(small, '#ffffff', null))),
  };
}

