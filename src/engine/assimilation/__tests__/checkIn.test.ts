// ------------------------------------------------------------------------------------------- D5-08 behaviour paths
/**
 * D5-08 provider/consumer fixture: what the replay needs from a behaviour forecast. A mean utility credit (the decayed
 * Beta(6,2) adherence summary) is neither p(done) nor a dose. A behaviour scenario is a set of complete dose paths
 * (done/skipped opportunities with their real fast durations), each simulated through the nonlinear engine BEFORE the
 * outcomes are averaged. The sampler below is a test-local reference: independent per-opportunity probability p (a stated
 * scenario assumption), a seed keyed to plan id, plan version and stable path index, one draw per opportunity, opportunities
 * on distinct days. The production sampler belongs to the living/planner owners.
 */
describe('behaviour scenarios reach the replay as complete dose paths, never as utility credit (D5-08)', () => {
  const HB = 28;
  const BASE: Schedule = { ...PLAN, horizonDays: HB, days: PLAN.days.slice(0, HB) };
  // three prescribed 36 h fasts, 20:00 → 08:00 two days later (the last one ends on the morning of day 19)
  const FASTS: readonly FastEvent[] = [3, 10, 17].map((d) => ({ kind: 'fast' as const, startDay: d, startH: 20, durationH: 36 }));
  const replays = new Map<string, ReplayOutput>();
  /** One replay per distinct dose path: identical doses give an identical deterministic outcome, so paths share runs. */
  const replayOf = (events: readonly FastEvent[]): ReplayOutput => {
    const key = JSON.stringify(events);
    let r = replays.get(key);
    if (!r) {
      r = runReplay({ profile: MAN, schedule: { ...BASE, events: [...events] } });
      replays.set(key, r);
    }
    return r;
  };
  const pathEvents = (done: readonly boolean[]): FastEvent[] => FASTS.filter((_, k) => done[k]);
  const KEYS = ['scaleFastEndKg', 'scaleEndKg', 'fatEndKg'] as const;
  type Outcome = Record<(typeof KEYS)[number], number>;
  /** Outcomes are read from each simulated path: scale the morning the last fast ends, scale and fat at the horizon. */
  const outcome = (r: ReplayOutput): Outcome => ({ scaleFastEndKg: r.scaleWakeKg[19]!, scaleEndKg: r.scaleWakeKg[HB - 1]!, fatEndKg: r.fatKg[HB - 1]! });
  const combos = Array.from({ length: 2 ** FASTS.length }, (_, m) => FASTS.map((_, k) => ((m >> k) & 1) === 1));
  /** Exact path mixture over all 2^K done/skipped combinations. */
  const mixture = (p: number): Outcome => {
    const acc: Outcome = { scaleFastEndKg: 0, scaleEndKg: 0, fatEndKg: 0 };
    for (const c of combos) {
      const w = c.reduce((s, d) => s * (d ? p : 1 - p), 1);
      if (w === 0) continue;
      const o = outcome(replayOf(pathEvents(c)));
      for (const k of KEYS) acc[k] += w * o[k];
    }
    return acc;
  };
  const NONE = outcome(replayOf([]));
  const ALL = outcome(replayOf(FASTS));
  /** The retired rule: a mean credit ≥ 0.5 switches every fast on. */
  const switchRule = (meanCredit: number): Outcome => (meanCredit >= 0.5 ? ALL : NONE);
  /** The retired dose: every fast shortened by the mean credit (a fractional dose nobody performed). */
  const fractionalDose = (c: number): Outcome => outcome(replayOf(c > 0 ? FASTS.map((e) => ({ ...e, durationH: e.durationH * c })) : []));
  const pathSeed = (planId: string, planVersion: number, path: number): number => Number.parseInt(contentHash({ planId, planVersion, path }).slice(0, 8), 16);
  /** Seeded path ensemble; path k has its own stream, so the same draws are reused across p (common random numbers). */
  const ensemble = (p: number, n: number, planVersion = 3) => {
    const paths: Outcome[] = [];
    for (let k = 0; k < n; k++) {
      const u = mulberry32(pathSeed('plan-a', planVersion, k));
      paths.push(outcome(replayOf(pathEvents(FASTS.map(() => u() < p)))));
    }
    const mean = {} as Outcome;
    const se = {} as Outcome;
    for (const k of KEYS) {
      const m = paths.reduce((s, o) => s + o[k], 0) / n;
      mean[k] = m;
      se[k] = Math.sqrt(paths.reduce((s, o) => s + (o[k] - m) ** 2, 0) / Math.max(1, n - 1) / n);
    }
    const meta = { algorithm: 'pathEnsemble', version: 1, seed: pathSeed('plan-a', planVersion, 0), paths: n, calibration: 'heuristic' } satisfies BehaviorForecastMeta;
    return { paths, mean, se, meta };
  };

  it('a mean credit is not p(done): the path mixture moves continuously with p, the retired 0.5 switch jumps by the whole difference', () => {
    for (const k of KEYS) {
      const jump = Math.abs(ALL[k] - NONE[k]);
      expect(jump).toBeGreaterThan(0);
      // the end points are the complete paths themselves
      expect(mixture(0)[k]).toBe(NONE[k]);
      expect(mixture(1)[k]).toBe(ALL[k]);
      // across 0.49 → 0.51 the mixture moves by a few percent of the done-vs-skipped difference ...
      expect(Math.abs(mixture(0.51)[k] - mixture(0.49)[k])).toBeLessThanOrEqual(0.05 * jump + 1e-9);
      // ... while a credit threshold turns every fast on at once
      expect(Math.abs(switchRule(0.51)[k] - switchRule(0.49)[k])).toBe(jump);
    }
    // the Beta(6,2) summary mean 0.75 under the retired rule would simulate every fast as done
    expect(switchRule(0.75)).toEqual(ALL);
  });

  it('averaging simulated paths is not simulating the average dose: E[f(D)] ≠ f(E[D]) at equal expected fasting hours', () => {
    const mix = mixture(0.5);
    const frac = fractionalDose(0.5);
    // both carry 54 h of expected fasting; the half-length fasts are a dose nobody performed
    expect(Math.abs(frac.scaleFastEndKg - mix.scaleFastEndKg)).toBeGreaterThan(0.05);
    for (const k of KEYS) expect(Number.isFinite(frac[k] - mix[k])).toBe(true);
  });

  it('seeded paths replay exactly, keep their draws when paths are added, and converge to the mixture within Monte Carlo error', () => {
    const a = ensemble(0.6, 64);
    expect(ensemble(0.6, 64)).toEqual(a);
    const b = ensemble(0.6, 128);
    expect(b.paths.slice(0, 64)).toEqual(a.paths);
    // another plan version is another stream
    expect(ensemble(0.6, 64, 4).paths).not.toEqual(a.paths);
    const exact = mixture(0.6);
    for (const k of KEYS) expect(Math.abs(b.mean[k] - exact[k])).toBeLessThanOrEqual(4 * b.se[k] + 1e-9);
    // the forecast semantics travel with the numbers: heuristic until prospective calibration exists
    expect(b.meta.calibration).toBe('heuristic');
    expect(JSON.parse(JSON.stringify(b.meta))).toEqual(b.meta);
  });

  it('one finite seeded realisation is stepwise in p, with steps far below the switch (convergence, not literal smoothness)', () => {
    for (const k of KEYS) {
      const jump = Math.abs(ALL[k] - NONE[k]);
      let prev = ensemble(0, 64).mean[k];
      let maxStep = 0;
      for (let i = 1; i <= 50; i++) {
        const m = ensemble(i / 50, 64).mean[k];
        maxStep = Math.max(maxStep, Math.abs(m - prev));
        prev = m;
      }
      expect(prev).toBeCloseTo(ALL[k], 9);
      expect(maxStep).toBeLessThanOrEqual(0.2 * jump);
    }
    // every path above is one of the 2^K dose combinations: nothing fractional was simulated
    expect(replays.size).toBeLessThanOrEqual(combos.length + 1);
  });

  it('the check-in fits one net residual against the doses actually taken; replaying credit-switched fasts manufactures one', () => {
    // prescribed: a zero-energy day every Friday; performed: only on even weeks (logged complete, so calibration-eligible)
    const actualPlan: Schedule = { ...FAST_PLAN, days: FAST_PLAN.days.map((x, d) => ({ program: x.program === 2 && Math.floor(d / 7) % 2 === 1 ? 1 : x.program })) };
    const truthA = runReplay({ profile: MAN, schedule: actualPlan });
    const w: WeighInObs[] = Array.from({ length: 29 }, (_, d) => ({ day: d, scaleKg: truthA.scaleWakeKg[d]!, context: 'standardized' as const, observationId: `a${d}` }));
    const evidence: IntakeDayEvidence[] = allDays.filter((d) => d < 28).map((d) => ({ day: d, coverage: 'complete' }));
    const run = (schedule: Schedule) => runCheckIn({ day: 28, profile: MAN, schedule, anchors: [], intakeOffsets: [], weighIns: w, startWeekday: 0, intakeDays: allDays, intakeEvidence: evidence, previousBias: { mean: 0, sd: 150 } });
    const actual = run(actualPlan);
    const switched = run(FAST_PLAN); // every prescribed fast simulated as done (the retired E[c] ≥ 0.5 rule)
    expect(actual.bias.updated).toBe(true);
    expect(Math.abs(actual.bias.measurement!.value)).toBeLessThan(30);
    // the skipped fasts reappear as a positive "balance error" the controller would then correct
    expect(switched.bias.measurement!.value).toBeGreaterThan(100);
    expect(switched.bias.mean).toBeGreaterThan(actual.bias.mean);
    // both report one net residual, never split into intake error versus expenditure
    expect(actual.intakeEvidence!.interpretation).toBe('netResidual');
    expect(switched.intakeEvidence!.interpretation).toBe('netResidual');
    expect(actual.estimator).toEqual(switched.estimator);
  });

  it('repeated same-day readings are one day of evidence: gate, trend and δ ignore the repeats; each id is consumed once', () => {
    const day = 28;
    const ids = weighIns.filter((o) => o.day <= day).map((o) => ({ ...o, observationId: `wt-${o.day}` }));
    const repeated = ids.flatMap((o) => [o, { ...o, observationId: `${o.observationId}-b` }, { ...o, observationId: `${o.observationId}-c` }]);
    const base = { day, profile: MAN, schedule: PLAN, anchors: [] as AnchorSpec[], intakeOffsets: [] as IntakeOffset[], startWeekday: 0, intakeDays: allDays, previousBias: { mean: 0, sd: 150 } };
    const one = runCheckIn({ ...base, weighIns: ids });
    const three = runCheckIn({ ...base, weighIns: repeated });
    expect(three.in7).toBe(one.in7);
    expect(three.in14).toBe(one.in14);
    // (equal up to the rounding of a mean of identical values: the merged reading keeps one reading's variance)
    for (const k of ['w', 'wSd', 'r', 'rSd'] as const) expect(three.trend![k]).toBeCloseTo(one.trend![k], 9);
    expect(three.bias.updated).toBe(one.bias.updated);
    expect(three.bias.mean).toBeCloseTo(one.bias.mean, 6);
    expect(three.bias.sd).toBeCloseTo(one.bias.sd, 6);
    expect(three.bias.measurement!.se).toBeCloseTo(one.bias.measurement!.se, 6);
    expect(three.bias.measurement!.n).toBe(one.bias.measurement!.n);
    expect(three.anchor!.tissueMassKg).toBeCloseTo(one.anchor!.tissueMassKg, 9);
    expect(three.consumedObservationIds).toHaveLength(new Set(three.consumedObservationIds).size);
    expect(three.consumedObservationIds.length).toBe(3 * one.consumedObservationIds.length);
    // six readings on two mornings are two days, below the 4-in-7 gate
    const twoMornings = [25, 25, 25, 27, 27, 27].map((d, k) => ({ day: d, scaleKg: 90, observationId: `r${k}` }));
    const gated = runCheckIn({ ...base, weighIns: twoMornings });
    expect(gated.in7).toBe(2);
    expect(gated.verdict).toBe('notEnoughWeighIns');
    expect(gated.consumedObservationIds).toEqual([]);
  });

  it('quiet mode: no weigh-ins means no decision and no fabricated estimate; the previous correction stays in force', () => {
    const quiet = runCheckIn({ day: 28, profile: MAN, schedule: PLAN, anchors: [], intakeOffsets: [{ fromDay: 14, kcal: -100 }], weighIns: [], startWeekday: 0, intakeDays: [], previousBias: { mean: -100, sd: 120 } });
    expect(quiet.verdict).toBe('notEnoughWeighIns');
    expect(quiet.trend).toBeNull();
    expect(quiet.anchor).toBeNull();
    expect(quiet.intakeOffset).toBeNull();
    expect(quiet.correction).toBeNull();
    expect(quiet.bias).toEqual({ mean: -100, sd: 120, updated: false });
    expect(quiet.consumedObservationIds).toEqual([]);
    expect(JSON.parse(JSON.stringify(quiet))).toEqual(quiet);
  });
});

describe('prospective scoring of frozen decisions on untouched future weeks (D5-08 calibration fixture)', () => {
  const HORIZON = 14;
  /**
   * Rolling origins: each confirmed decision is frozen, then its forecast of the next two weeks is scored on readings it
   * never consumed, beside the uncorrected model from the same anchored state and the filter's own trend extrapolation.
   */
  const scoreOrigins = (origins: readonly CheckInOutput[], readings: readonly WeighInObs[]) => {
    const corrected: PointForecast[] = [];
    const uncorrected: PointForecast[] = [];
    const extrapolated: PointForecast[] = [];
    for (const o of origins) {
      const nominal = runReplay({ profile: MAN, schedule: PLAN, from: o.snapshot! });
      for (const w of readings.filter((x) => x.day > o.day && x.day <= o.day + HORIZON)) {
        corrected.push({ y: w.scaleKg, mu: o.replay!.scaleWakeKg[w.day]! });
        uncorrected.push({ y: w.scaleKg, mu: nominal.scaleWakeKg[w.day]! });
        extrapolated.push({ y: w.scaleKg, mu: o.trend!.w + o.trend!.r * (w.day - o.day) + o.replay!.waterWakeKg[w.day]! });
      }
    }
    return { corrected: pointScores(corrected)!, uncorrected: pointScores(uncorrected)!, extrapolated: pointScores(extrapolated)! };
  };

  it('readings after the decision day never reach the decision (the held-out block stays untouched)', () => {
    const ids = weighIns.map((o) => ({ ...o, observationId: `wt-${o.day}` }));
    const base = { day: 28, profile: MAN, schedule: PLAN, anchors: [] as AnchorSpec[], intakeOffsets: [] as IntakeOffset[], startWeekday: 0, intakeDays: allDays, previousBias: { mean: 0, sd: 150 } };
    const train = runCheckIn({ ...base, weighIns: ids.filter((o) => o.day <= 28) });
    const all = runCheckIn({ ...base, weighIns: ids });
    expect(all.bias).toEqual(train.bias);
    expect(all.trend).toEqual(train.trend);
    expect(all.anchor).toEqual(train.anchor);
    expect(all.consumedObservationIds).toEqual(train.consumedObservationIds);
    expect(all.consumedObservationIds.every((id) => Number(id.slice(3)) <= 28)).toBe(true);
    expect(all.snapshot!.key).toBe(train.snapshot!.key);
  });

  it('noisy, gappy weigh-ins: bias and MAE of every forecaster are reported on the same held-out readings; one net residual, no causes', () => {
    const report = scoreOrigins(outs.filter((o) => o.day + HORIZON <= H - 1), weighIns);
    for (const r of Object.values(report)) {
      expect(r.n).toBe(report.corrected.n);
      for (const v of Object.values(r)) expect(Number.isFinite(v)).toBe(true);
    }
    expect(report.corrected.n).toBeGreaterThan(50);
    // hidden δ = −250 kcal/d: the nominal model over-predicts the next two weeks (no forecaster is required to win here)
    expect(report.uncorrected.bias).toBeGreaterThan(0);
    // the decision carries one predictive residual and its labels, never shares of intake, expenditure or adherence
    for (const o of outs) {
      const keys = [...Object.keys(o.bias), ...Object.keys(o.correction ?? {}), ...Object.keys(o.biasDiagnostics ?? {})];
      for (const k of keys) expect(k).not.toMatch(/cause|share|hormon|neat|rmr|adherence|expenditure|intakeError/i);
      if (o.bias.updated) {
        expect(o.bias.uncertaintyKind).toBe('conditionalResidual');
        expect(o.bias.coverage).toBe('unvalidated');
      }
    }
  });

  it('noise-free weigh-ins: the forward replay of the applied correction removes part of the held-out bias (algebra check)', () => {
    const exact: WeighInObs[] = Array.from({ length: H }, (_, d) => ({ day: d, scaleKg: truth.scaleWakeKg[d]!, context: 'standardized' as const }));
    const c: Carry = { anchors: [], offsets: [], bias: { mean: 0, sd: 150 } };
    const origins: CheckInOutput[] = [];
    for (let day = 14; day + HORIZON <= H - 1; day += 7) {
      const o = runCheckIn({ day, profile: MAN, schedule: PLAN, anchors: c.anchors, intakeOffsets: c.offsets, weighIns: exact.filter((w) => w.day <= day), startWeekday: 0, intakeDays: allDays, previousBias: c.bias });
      origins.push(o);
      c.anchors = [...c.anchors.filter((a) => a.day !== day), o.anchor!];
      if (o.intakeOffset) c.offsets = [...c.offsets, o.intakeOffset];
      c.bias = { mean: o.bias.mean, sd: o.bias.sd };
    }
    const report = scoreOrigins(origins, exact);
    // the fixed prior shrinks each request toward 0 and the controller caps its steps, so the residual removes part of the
    // bias, not all of it (engine-generated truth: verification of the algebra, not external validation)
    expect(origins.every((o) => o.bias.mean < 0)).toBe(true);
    expect(report.uncorrected.bias).toBeGreaterThan(0);
    expect(Math.abs(report.corrected.bias)).toBeLessThan(0.85 * report.uncorrected.bias);
    expect(report.corrected.mae).toBeLessThan(report.uncorrected.mae);
  });
});
