// ------------------------------------------------------------------------------------------- D5-03 applied history
const ZERO_DAY: DayTemplate = { ...REST, id: 'Z', label: 'fast day', energy: { kind: 'zero' } };
const FAST_PATTERN = [0, 1, 0, 1, 2, 1, 1];
const FAST_PLAN: Schedule = { ...PLAN, programs: [TRAIN, REST, ZERO_DAY], days: Array.from({ length: H }, (_, d) => ({ program: FAST_PATTERN[d % 7]! })) };

describe('balance correction against its actual application history (D5-03)', () => {
  const TRUE = -200;
  const truthF = runReplay({ profile: MAN, schedule: FAST_PLAN, intakeOffsets: [{ fromDay: 0, kcal: TRUE }] });
  const exact: WeighInObs[] = Array.from({ length: 22 }, (_, d) => ({ day: d, scaleKg: truthF.scaleWakeKg[d]!, context: 'standardized' as const, observationId: `w${d}` }));
  const piecewise: IntakeOffset[] = [{ fromDay: 0, kcal: 0 }, { fromDay: 7, kcal: 100 }, { fromDay: 14, kcal: 200 }];
  const out = runCheckIn({ day: 21, profile: MAN, schedule: FAST_PLAN, anchors: [], intakeOffsets: piecewise, weighIns: exact, startWeekday: 0, intakeDays: allDays, previousBias: { mean: 200, sd: 150 } });

  it('piecewise 0/100/200 kcal/d with weekly fast days: the window replay recovers the forward-model residual', () => {
    expect(out.bias.updated).toBe(true);
    const m = out.bias.measurement!;
    expect(m.method).toBe('replayResidual');
    expect(out.biasDiagnostics!.replayRuns).toBeGreaterThanOrEqual(2);
    expect(Math.abs(m.value - TRUE)).toBeLessThan(15);
    // the latest offset is not the application history (only a constant application makes "latest δ" exact)
    expect(out.biasDiagnostics!.constantApplication).toBe(false);
  });

  it('constant-offset limiting case: the replay recovers the residual exactly; the linear diagnostic is the old algebra', () => {
    const constant = runCheckIn({ day: 21, profile: MAN, schedule: FAST_PLAN, anchors: [], intakeOffsets: [{ fromDay: 0, kcal: TRUE }], weighIns: exact, startWeekday: 0, intakeDays: allDays, previousBias: { mean: TRUE, sd: 150 } });
    expect(constant.biasDiagnostics!.constantApplication).toBe(false); // fast days apply nothing even under a constant request
    expect(constant.bias.measurement!.value).toBeCloseTo(TRUE, 1);
    // the nonlinear response (TEF and macro-scaled channels) is in the replay, not in a constant-density reading
    const lin = constant.biasDiagnostics!.linear!.value;
    expect(Math.abs(constant.bias.measurement!.value - TRUE)).toBeLessThan(Math.abs(lin - TRUE));
  });

  it('the realised ledger skips zero-energy days (A is flat there) and is the one the linear diagnostic uses', () => {
    const fastDays = out.offsetsApplied.filter((a) => FAST_PATTERN[a.day % 7] === 2);
    expect(fastDays.length).toBeGreaterThan(0);
    for (const a of fastDays) {
      expect(a.appliedKcal).toBe(0);
      expect(a.skippedReason).toBe('zeroEnergyDay');
    }
    for (const a of out.offsetsApplied.filter((x) => FAST_PATTERN[x.day % 7] !== 2)) expect(a.appliedKcal).toBeCloseTo(a.requestedKcal, 6);
    expect(out.offsetsApplied.every((a) => a.day < 21)).toBe(true);
    // the linear diagnostic (ρ constant) is reported, not used as the production value
    expect(out.biasDiagnostics!.linear!.method).toBe('linearAppliedHistory');
  });

  it('a constant application with a zero correction exactly preserves the uncorrected simulation', () => {
    const a = runReplay({ profile: MAN, schedule: PLAN });
    const b = runReplay({ profile: MAN, schedule: PLAN, intakeOffsets: [{ fromDay: 0, kcal: 0 }] });
    for (let d = 0; d < H; d++) expect(b.scaleWakeKg[d]).toBe(a.scaleWakeKg[d]);
    expect(b.offsetsApplied).toEqual([]);
  });

  it('a correction never mutates the logged intake: protein, carbohydrate and energy echoes stay as logged', () => {
    const a = runReplay({ profile: MAN, schedule: FAST_PLAN });
    const b = runReplay({ profile: MAN, schedule: FAST_PLAN, intakeOffsets: [{ fromDay: 0, kcal: -250 }] });
    for (const k of ['inProtein', 'inCarbs', 'inFat', 'inEnergy'] as const) {
      const xa = a.result.daily[k]!;
      const xb = b.result.daily[k]!;
      for (let d = 0; d < H; d++) expect(xb[d]).toBe(xa[d]);
    }
    // the stored law is the absorbed-macro imputation (an intake-side scenario)
    expect(b.correction.mechanism).toBe('absorbedMacroImputation');
    // legacy offsets without a mechanism have the same meaning
    const c = runReplay({ profile: MAN, schedule: FAST_PLAN, intakeOffsets: [{ fromDay: 0, kcal: -250, mechanism: 'absorbedMacroImputation' }] });
    for (let d = 0; d < H; d++) expect(c.scaleWakeKg[d]).toBe(b.scaleWakeKg[d]);
  });

  it('an expenditure-side truth keeps acting on fast days, the intake-side correction does not: distinct hypotheses', () => {
    // an extra-expenditure truth (more steps every day, fast days included) versus the intake-side law
    const moreSteps: Schedule = { ...FAST_PLAN, programs: FAST_PLAN.programs.map((p) => ({ ...p, steps: (p.steps ?? 8000) + 4000 })) };
    const exp = runReplay({ profile: MAN, schedule: moreSteps });
    const base = runReplay({ profile: MAN, schedule: FAST_PLAN });
    const intake = runReplay({ profile: MAN, schedule: FAST_PLAN, intakeOffsets: [{ fromDay: 0, kcal: -200 }] });
    const fast = 4 + 7; // a zero-energy day
    const dExp = (exp.tissuePathKg[fast + 1]! - exp.tissuePathKg[fast]!) - (base.tissuePathKg[fast + 1]! - base.tissuePathKg[fast]!);
    const dInt = (intake.tissuePathKg[fast + 1]! - intake.tissuePathKg[fast]!) - (base.tissuePathKg[fast + 1]! - base.tissuePathKg[fast]!);
    expect(dExp).toBeLessThan(-0.005);
    expect(Math.abs(dInt)).toBeLessThan(Math.abs(dExp) / 2);
    expect(intake.offsetsApplied.find((a) => a.day === fast)!.skippedReason).toBe('zeroEnergyDay');
  });

  it('the same observations cannot earn another weekly step; no new weigh-in → no update (retry-safe)', () => {
    const truthBig = runReplay({ profile: MAN, schedule: PLAN, intakeOffsets: [{ fromDay: 0, kcal: -700 }] });
    const w: WeighInObs[] = Array.from({ length: 30 }, (_, d) => ({ day: d, scaleKg: truthBig.scaleWakeKg[d]! }));
    const first = runCheckIn({ day: 21, profile: MAN, schedule: PLAN, anchors: [], intakeOffsets: [], weighIns: w.filter((o) => o.day <= 21), startWeekday: 0, intakeDays: allDays, previousBias: { mean: 0, sd: 150 } });
    expect(first.bias.updated).toBe(true);
    expect(first.bias.mean).toBe(-100);
    expect(first.bias.stepLimited).toBe(true);
    expect(first.bias.requestedKcal!).toBeLessThan(-100);
    const carryA = [first.anchor!];
    const carryO = [first.intakeOffset!];
    expect(carryO[0]!.requestedKcal).toBe(first.bias.requestedKcal);
    // a retry the next day with the same weigh-ins: no new evidence, nothing changes
    const retry = runCheckIn({ day: 22, profile: MAN, schedule: PLAN, anchors: carryA, intakeOffsets: carryO, weighIns: w.filter((o) => o.day <= 21), startWeekday: 0, intakeDays: allDays, previousBias: { mean: first.bias.mean, sd: first.bias.sd } });
    expect(retry.bias.updated).toBe(false);
    expect(retry.bias.reason).toBe('noNewEvidence');
    expect(retry.intakeOffset).toBeNull();
    // one more weigh-in the next day: the step still counts from the value in force a week before (0), so no second step
    const again = runCheckIn({ day: 22, profile: MAN, schedule: PLAN, anchors: carryA, intakeOffsets: carryO, weighIns: w.filter((o) => o.day <= 22), startWeekday: 0, intakeDays: allDays, previousBias: { mean: first.bias.mean, sd: first.bias.sd } });
    expect(again.bias.updated).toBe(true);
    expect(again.bias.mean).toBeGreaterThanOrEqual(-100);
    expect(again.intakeOffset).toBeNull();
  });
});

