describe('A1-018: measurements sit at their own occurrence and are compared through their own-time operator', () => {
  it('a backfill with an instant yesterday is placed yesterday even when the record carries the entry date', () => {
    const at = '2026-10-10T07:30:00+05:30';
    const legacyCommand: MeasurementEntry = { id: 'b', date: '2026-10-11', metric: 'weightKg', value: 90, source: SRC, occurrence: { ...exactOccurrence(at, { tz: 'Asia/Kolkata', date: '2026-10-11', dateMeaning: 'appDay' }) } };
    // the record date (entry day) contradicts the instant: kept as submitted, flagged, the instant places the reading
    expect(measurementSample(PLAN, legacyCommand)).toEqual({ day: 5, timing: { precision: 'instant', hour: 7.5 }, dateConflict: true });
    const fixedCommand: MeasurementEntry = { ...legacyCommand, date: '2026-10-10', occurrence: exactOccurrence(at, { tz: 'Asia/Kolkata', date: '2026-10-10', dateMeaning: 'appDay' }) };
    expect(measurementSample(PLAN, fixedCommand)).toEqual({ day: 5, timing: { precision: 'instant', hour: 7.5 } });
    // an instant before the app-day rollover keeps its app date without a conflict
    const lateNight: MeasurementEntry = { ...legacyCommand, date: '2026-10-09', occurrence: { ...exactOccurrence('2026-10-10T01:30:00+05:30', { tz: 'Asia/Kolkata', date: '2026-10-09', dateMeaning: 'appDay' }), rolloverH: 4 } };
    expect(measurementSample(PLAN, lateNight)).toEqual({ day: 5, timing: { precision: 'instant', hour: 1.5 } });
    expect(weighInsFor(PLAN, [legacyCommand], [])[0]).toMatchObject({ day: 5, timing: { precision: 'instant', hour: 7.5 } });
    // the recorded time alone never changes placement or state
    const later = { ...legacyCommand, recordedAt: '2026-10-20T10:00:00Z', at: '2026-10-20T10:00:00Z' };
    expect(weighInsFor(PLAN, [later], [])).toEqual(weighInsFor(PLAN, [legacyCommand], []));
  });

  it('instants on opposite sides of midnight and across the DST fold follow the declared zone', () => {
    const mk = (id: string, at: string, date = '2026-10-25'): MeasurementEntry => ({ id, date, metric: 'weightKg', value: 90, source: SRC, occurrence: exactOccurrence(at, { tz: 'Europe/London' }) });
    expect(measurementSample(PLAN, mk('a', '2026-10-24T22:30:00Z', '2026-10-24'))).toEqual({ day: 19, timing: { precision: 'instant', hour: 23.5 } });
    expect(measurementSample(PLAN, mk('b', '2026-10-24T23:30:00Z'))).toEqual({ day: 20, timing: { precision: 'instant', hour: 0.5 } });
    // 01:30 happens twice on 25 October (BST, then GMT): both are hour 1.5 of the same local day
    expect(measurementSample(PLAN, mk('c', '2026-10-25T00:30:00Z')).timing.hour).toBeCloseTo(1.5, 9);
    expect(measurementSample(PLAN, mk('d', '2026-10-25T01:30:00Z')).timing.hour).toBeCloseTo(1.5, 9);
    // without a zone the offset the instant was written with is its local clock
    const noZone: MeasurementEntry = { id: 'e', date: '2026-10-24', metric: 'weightKg', value: 90, source: SRC, occurrence: { precision: 'exact', at: '2026-10-24T23:50:00-04:00', dateMeaning: 'unknown', source: 'user' } };
    expect(measurementSample(PLAN, noZone)).toEqual({ day: 19, timing: { precision: 'instant', hour: 23 + 50 / 60 } });
  });

  it('morning and post-refeed evening readings from one model path give near-zero residuals through their own operators', () => {
    const FAST = waterOnlyProgram('fast');
    const sched: Schedule = { ...PLAN_SCHEDULE, programs: [TRAIN, REST, FAST], days: PLAN_SCHEDULE.days.map((d, k) => (k === 12 ? { program: 2 } : d)) };
    const r = runReplay({ profile: MAN, schedule: sched, hourly: true });
    const d = 13;
    const fm = r.fatKg[d - 1]!;
    const scaleAt = (h: number) => r.scaleHourKg![d * 24 + h]!;
    expect(scaleAt(21) - scaleAt(7)).toBeGreaterThan(0.5);
    const morning: CompositionReading = { observationId: 'm', day: d, method: 'bia', bodyFatPct: (100 * fm) / scaleAt(7), device: 'x', timing: { precision: 'instant', hour: 7.2 } };
    const evening: CompositionReading = { observationId: 'e', day: d, method: 'bia', bodyFatPct: (100 * fm) / scaleAt(21), device: 'y', timing: { precision: 'instant', hour: 21.5 } };
    const target = (readings: CompositionReading[]) =>
      compositionTarget({ day: 20, targetTissueKg: r.tissueWakeKg[20]!, engineFatKg: r.fatKg[19]!, fatShareOfResidual: 0.8, readings: { readings }, replay: r, trendAt: (k) => ({ tissueKg: r.tissueWakeKg[k]!, sdKg: 0.1 }) });
    const u = target([morning, evening]);
    for (const x of u.used) expect(Math.abs(x.innovationKg)).toBeLessThan(0.05);
    expect(u.used.map((x) => x.at)).toEqual(['hour', 'hour']);
    expect(u.assumptions).toContain('hourlyModelMass');
    // the evening percentage read as a wake reading would manufacture a fat innovation (the old operator)
    const untimed = target([{ ...evening, timing: undefined }]);
    expect(Math.abs(untimed.used[0]!.innovationKg)).toBeGreaterThan(5 * Math.abs(u.used.find((x) => x.observationId === 'e')!.innovationKg));
    // the same evening scale weight minus the model water of that hour is the same water-adjusted mass as the morning one
    const yMorning = scaleAt(7) - r.waterHourKg![d * 24 + 7]!;
    const yEvening = scaleAt(21) - sampleAt(r.waterHourKg, r.waterWakeKg, d, { precision: 'instant', hour: 21.5 })!.kg;
    expect(Math.abs(yEvening - yMorning)).toBeLessThan(0.1);
    expect(Math.abs(scaleAt(21) - r.waterWakeKg[d]! - yMorning)).toBeGreaterThan(0.4);
  });

  it('timed weigh-ins move no tissue anchor: the check-in removes the model water of each reading’s hour', () => {
    const r = runReplay({ profile: MAN, schedule: PLAN_SCHEDULE, hourly: true });
    const morning: WeighInObs[] = Array.from({ length: 22 }, (_, d) => ({ day: d, scaleKg: r.scaleWakeKg[d]!, context: 'standardized' as const }));
    const evening: WeighInObs[] = morning.map((o) => ({ ...o, scaleKg: r.scaleHourKg![o.day * 24 + 20]!, context: 'unstandardized' as const, timing: { precision: 'instant' as const, hour: 20.25 } }));
    const base = { day: 21, profile: MAN, schedule: PLAN_SCHEDULE, anchors: [], intakeOffsets: [], startWeekday: 0, intakeDays: [], previousBias: { mean: 0, sd: 150 } };
    const a = runCheckIn({ ...base, weighIns: morning });
    const b = runCheckIn({ ...base, weighIns: evening });
    // each residualised observation is the reading minus the model water OF ITS HOUR (not the wake water)
    for (const d of [3, 10, 17]) {
      const y = b.points.find((p) => p.day === d)!.y!;
      expect(y).toBeCloseTo(r.scaleHourKg![d * 24 + 20]! - r.waterHourKg![d * 24 + 20]!, 9);
      expect(Math.abs(y - (r.scaleHourKg![d * 24 + 20]! - r.waterWakeKg[d]!))).toBeGreaterThan(1e-3);
    }
    // the same path read in the evening anchors the same tissue (within-day tissue change only, no water artefact)
    expect(Math.abs(b.anchor!.tissueMassKg - a.anchor!.tissueMassKg)).toBeLessThan(0.15);
  });

  it('date-only and unknown-context readings stay usable, labelled date-only, never standardized morning instants', () => {
    const ms: MeasurementEntry[] = [
      { id: 'w1', date: '2026-10-07', metric: 'weightKg', value: 91, source: SRC },
      { id: 'w2', date: '2026-10-08', metric: 'weightKg', value: 90.8, context: 'evening', source: SRC, occurrence: intervalOccurrence('2026-10-08T18:00:00+05:30', '2026-10-08T21:00:00+05:30', { tz: 'Asia/Kolkata' }) },
      { id: 'bf', date: '2026-10-09', metric: 'bodyFatPct', value: 24, method: 'bia', source: SRC },
    ];
    const w = weighInsFor(PLAN, ms, []);
    expect(w[0]).toMatchObject({ day: 2, context: 'unknown', standardised: false, timing: { precision: 'dateOnly' } });
    expect(w[1]).toMatchObject({ day: 3, timing: { precision: 'interval', hourSpan: [18, 21] } });
    expect(runTrendFilter(w).meta.timing).toEqual({ instant: 0, interval: 1, dateOnly: 1, unknown: 0 });
    const obs = compositionObservations(PLAN, ms);
    expect(obs[0]).toMatchObject({ day: 4, timing: { precision: 'dateOnly' }, occurrence: { precision: 'dateOnly' } });
    const r = runReplay({ profile: MAN, schedule: PLAN_SCHEDULE });
    const u = compositionTarget({ day: 7, targetTissueKg: r.tissueWakeKg[7]!, engineFatKg: r.fatKg[6]!, fatShareOfResidual: 0.8, readings: compositionReadingsFor(PLAN, ms), replay: r, trendAt: () => null });
    expect(u.status).toBe('updated');
    expect(u.used[0]).toMatchObject({ timing: 'dateOnly', at: 'wakeConvention' });
    expect(u.assumptions).toContain('dailyWakeConvention');
    // a timed percent reading without an hourly path abstains rather than borrowing the wake mass
    const timed = compositionTarget({ day: 7, targetTissueKg: r.tissueWakeKg[7]!, engineFatKg: r.fatKg[6]!, fatShareOfResidual: 0.8, readings: { readings: [{ observationId: 't', day: 4, method: 'bia', bodyFatPct: 24, timing: { precision: 'instant', hour: 20 } }] }, replay: r, trendAt: () => null });
    expect(timed.skipped[0]!.reason).toBe('instantOperatorUnavailable');
  });
});

