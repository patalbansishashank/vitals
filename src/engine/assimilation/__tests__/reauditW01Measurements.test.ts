describe('A1-017: a retracted or corrected reading leaves no stale composition anchor; originals are kept', () => {
  const truth = runReplay({ profile: MAN, schedule: PLAN_SCHEDULE, intakeOffsets: [{ fromDay: 0, kcal: -200 }] });
  const z = (() => {
    const u = mulberry32(11);
    return () => Math.sqrt(-2 * Math.log(1 - u())) * Math.cos(2 * Math.PI * u());
  })();
  const weights: MeasurementEntry[] = [];
  for (let d = 0; d < 28; d++) weights.push({ id: `w${d}`, date: dateOf(d), metric: 'weightKg', value: Math.round((truth.scaleWakeKg[d]! + 0.3 * z()) * 10) / 10, context: 'morningFasted', source: SRC });
  const dxa: MeasurementEntry = { id: 'dxa1', date: dateOf(13), metric: 'bodyFatPct', value: 16, method: 'dxa', scanMassKg: 92, source: SRC };
  const corrected: MeasurementEntry = { id: 'dxa2', date: dateOf(13), metric: 'bodyFatPct', value: 24, method: 'dxa', scanMassKg: 92, supersedes: 'dxa1', source: SRC };
  const retract = { id: 'r1', date: dateOf(13), metric: 'bodyFatPct', value: 16, kind: 'retract', target: 'dxa1', source: SRC } as unknown as MeasurementEntry;
  const intakeDays = Array.from({ length: 28 }, (_, d) => d);
  const weighIns = weighInsFor(PLAN, weights, []);
  const check = (day: number, records: readonly ConfirmedStateRecord[], ms: readonly MeasurementEntry[], params = ASSIMILATION_DEFAULTS) => {
    const composition = compositionReadingsFor(PLAN, ms);
    return weeklyCheckIn({ plan: PLAN, schedule: PLAN_SCHEDULE, records, weighIns: weighIns.filter((w) => w.day <= day), today: dateOf(day), intakeDays, ...(composition ? { composition } : {}), params, decisionId: `d${day}` });
  };
  const withDxa = check(14, [], [...weights, dxa]);
  const r14 = withDxa.record!;
  const clean14 = check(14, [], weights).record!;
  const cleanCorrected14 = check(14, [], [...weights, { ...corrected, supersedes: undefined }]).record!;

  it('the DXA reading anchors the composition at day 14 and records its lineage', () => {
    expect(r14.residualSplit.source).toBe('dxa');
    expect(r14.derivation?.observations.some((o) => o.id === 'dxa1')).toBe(true);
    expect(r14.compositionEvidence?.groups[0]).toMatchObject({ method: 'dxa', bias: 'unknownDevice', longitudinalSensitivity: 'unknown' });
    expect(clean14.residualSplit.source).toBe('engine');
  });

  it('retraction → automation daily replay equals a clean replay without the reading; the next check-in equals the clean chain', () => {
    const ms = [...weights, dxa, retract];
    expect(compositionReadingsFor(PLAN, ms)).toBeUndefined();
    const stale = dailyAssimilation({ plan: PLAN, schedule: PLAN_SCHEDULE, records: [r14], weighIns, today: dateOf(21) });
    const live = dailyAssimilation({ plan: PLAN, schedule: PLAN_SCHEDULE, records: [r14], weighIns, today: dateOf(21), composition: compositionReadingsFor(PLAN, ms) ?? null });
    const clean = dailyAssimilation({ plan: PLAN, schedule: PLAN_SCHEDULE, records: [clean14], weighIns, today: dateOf(21), composition: null });
    expect(live.current.invalidFrom).toBe(14);
    expect(live.current.chain[0]).toMatchObject({ origin: 'recomputed', reason: 'observationRetracted', compatibility: 'current' });
    // equal within numerical tolerance (float32 daily series; the recomputation replays only through its anchor morning)
    expect(live.current.anchors[0]!.tissueMassKg).toBeCloseTo(anchorsFromRecords([clean14]).anchors[0]!.tissueMassKg, 4);
    expect(live.current.anchors[0]!.split).toBeUndefined();
    expect(live.replay.fatKg[21]!).toBeCloseTo(clean.replay.fatKg[21]!, 4);
    // without the supplied graph the stored split is replayed unchanged (legacy behaviour): it is the stale effect
    expect(Math.abs(stale.replay.fatKg[21]! - clean.replay.fatKg[21]!)).toBeGreaterThan(1);
    const next = check(21, [r14], ms);
    const nextClean = check(21, [clean14], weights);
    expect(next.output.composition).toBeNull();
    expect(next.record!.residualSplit.tissueMassKg).toBeCloseTo(nextClean.record!.residualSplit.tissueMassKg, 4);
    expect(next.record!.residualSplit.fatKg).toBeCloseTo(nextClean.record!.residualSplit.fatKg, 4);
    expect(next.state!.snapshot.bus[0]).toBeCloseTo(nextClean.state!.snapshot.bus[0]!, 4);
    // the refit decision is the clean decision: same lineage fingerprint, so the chains coincide
    expect(next.record!.derivation!.previous).toBe(clean14.derivation!.fingerprint);
  });

  it('a corrected reading counts once at its corrected value (never a second independent effect)', () => {
    const ms = [...weights, dxa, corrected];
    const live = dailyAssimilation({ plan: PLAN, schedule: PLAN_SCHEDULE, records: [r14], weighIns, today: dateOf(21), composition: compositionReadingsFor(PLAN, ms) ?? null });
    const clean = dailyAssimilation({ plan: PLAN, schedule: PLAN_SCHEDULE, records: [cleanCorrected14], weighIns, today: dateOf(21), composition: compositionReadingsFor(PLAN, [...weights, { ...corrected, supersedes: undefined }]) ?? null });
    expect(live.current.chain[0]!.origin).toBe('recomputed');
    expect(live.current.derived[0]!.residualSplit.fatFrac).toBeCloseTo(cleanCorrected14.residualSplit.fatFrac!, 5);
    expect(live.replay.fatKg[21]!).toBeCloseTo(clean.replay.fatKg[21]!, 4);
    const next = check(21, [r14], ms);
    // the corrected reading was consumed by the refit day-14 decision: the day-21 decision has no new reading
    expect(next.output.composition!.status).toBe('noNewReadings');
  });

  it('reload, sync order, duplicates and repeated replay are idempotent; a cached recomputation is reused', () => {
    const ms = [...weights, dxa, retract];
    const a = currentAnchors({ plan: PLAN, schedule: PLAN_SCHEDULE, records: [r14], weighIns, composition: compositionReadingsFor(PLAN, ms) ?? null });
    const shuffled = [retract, ...weights.slice().reverse(), dxa, dxa];
    const b = currentAnchors({ plan: PLAN, schedule: PLAN_SCHEDULE, records: [r14, r14], weighIns: weighInsFor(PLAN, shuffled, []), composition: compositionReadingsFor(PLAN, shuffled) ?? null });
    expect(b.anchors).toEqual(a.anchors);
    expect(b.derived.map((d) => d.derivation.fingerprint)).toEqual(a.derived.map((d) => d.derivation.fingerprint));
    const cached = currentAnchors({ plan: PLAN, schedule: PLAN_SCHEDULE, records: [r14], weighIns, composition: null, derived: a.derived });
    expect(cached.derived[0]).toBe(a.derived[0]);
    expect(cached.anchors).toEqual(a.anchors);
    // with every original still valid nothing is recomputed
    const valid = currentAnchors({ plan: PLAN, schedule: PLAN_SCHEDULE, records: [r14], weighIns, composition: compositionReadingsFor(PLAN, [...weights, dxa]) ?? null });
    expect(valid.invalidFrom).toBeNull();
    expect(valid.chain[0]!.origin).toBe('original');
    expect(valid.anchors).toEqual(anchorsFromRecords([r14]).anchors);
  });

  it('an estimator change refits the current state while the original record stays byte-identical', () => {
    const before = JSON.stringify(r14);
    const prm = assimilationParams({ modelBfSdPct: 3 });
    expect(estimatorIdentity(prm).paramsHash).not.toBe(estimatorIdentity().paramsHash);
    const cur = currentAnchors({ plan: PLAN, schedule: PLAN_SCHEDULE, records: [r14], weighIns, composition: compositionReadingsFor(PLAN, [...weights, dxa]) ?? null, params: prm });
    expect(cur.chain[0]).toMatchObject({ origin: 'recomputed', reason: 'estimatorChanged' });
    expect(cur.derived[0]!.residualSplit.fatFrac).not.toBeCloseTo(r14.residualSplit.fatFrac!, 6);
    expect(JSON.stringify(r14)).toBe(before);
    // the original confirmed output stays reproducible from the record (history), bit for bit
    expect(Array.from(confirmedStateFromRecord(PLAN, PLAN_SCHEDULE, [r14], r14).snapshot.bus)).toEqual(Array.from(withDxa.state!.snapshot.bus));
    // a legacy record without lineage is never certified: it is recomputed (or historical only)
    const { derivation: _d, ...legacy } = r14;
    void _d;
    const leg = currentAnchors({ plan: PLAN, schedule: PLAN_SCHEDULE, records: [legacy], weighIns, composition: compositionReadingsFor(PLAN, [...weights, dxa]) ?? null });
    expect(leg.chain[0]).toMatchObject({ origin: 'recomputed', reason: 'legacyUnreconstructable', compatibility: 'current' });
    // a decision whose evidence is gone cannot be reproduced: historical only, left out of the current state
    const gone = currentAnchors({ plan: PLAN, schedule: PLAN_SCHEDULE, records: [r14], weighIns: [], composition: null });
    expect(gone.chain[0]!.compatibility).toBe('historicalOnly');
    expect(gone.anchors).toEqual([]);
  });

  it('recomputation adds no confirmation and no correction step: the applied ledger is the records’ own', () => {
    const r21 = check(21, [r14], [...weights, dxa]).record!;
    const records = [r14, r21];
    const ms = [...weights, dxa, retract];
    const cur = currentAnchors({ plan: PLAN, schedule: PLAN_SCHEDULE, records, weighIns, composition: compositionReadingsFor(PLAN, ms) ?? null });
    expect(cur.offsets).toEqual(anchorsFromRecords(records).offsets);
    expect(cur.chain.map((l) => l.origin)).toEqual(['recomputed', 'recomputed']);
    expect(cur.derived.every((d) => d.stamp.origin === 'recomputed' && d.energyBiasKcal === records.find((r) => r.anchorDay === d.anchorDay)!.energyBiasKcal)).toBe(true);
    expect(records).toHaveLength(2);
    expect(cur.derived.map((d) => d.sourceDecisionId)).toEqual(['d14', 'd21']);
  });
});

