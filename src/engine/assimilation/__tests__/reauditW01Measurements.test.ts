// ================================================================================================= A1-038
describe('A1-038: joint own-time state + shared device bias (change kept, absolute bias floor)', () => {
  const S = 0.72; // kg per percentage point at the 72 kg stub mass
  const P = (0.02 * 72) ** 2; // fixed prior of the path fat error (modelBfSdPct 2)
  const floorPct = (sys: number) => Math.sqrt(1 / (1 / (sys * sys) + (S * S) / P));

  /** m earlier decisions each consumed one same-device reading on the path (zero innovation), then one new reading. */
  const afterHistory = (m: number, newInnovKg: number, rep = 2.5, sys = 2.5) => {
    const days = Array.from({ length: m }, (_, k) => 7 * (k + 1));
    const r = fakeReplay(() => 20, { anchorDays: days });
    const prior: CompositionReading[] = days.map((d, k) => ({ observationId: `p${k}`, day: d - 1, method: 'bia', scanFatMassKg: 20, scanMassKg: 72, device: 'A', repeatabilitySdPct: rep, systematicSdPct: sys }));
    const day = 7 * (m + 1);
    const fresh: CompositionReading = { observationId: 'n', day: day - 1, method: 'bia', scanFatMassKg: 20 + newInnovKg, scanMassKg: 72, device: 'A', repeatabilitySdPct: rep, systematicSdPct: sys };
    return fakeTarget(r, day, { readings: [...prior, fresh] }, { consumed: new Set(prior.map((x) => x.observationId!)), history: days.map((d, k) => ({ day: d, consumed: [`p${k}`] })) });
  };

  it('repeatability 0 / systematic 2.5: a changed second reading is used, never consumed without information', () => {
    const u = afterHistory(1, -3, 0, 2.5);
    expect(u.status).toBe('updated');
    expect(u.consumedObservationIds).toEqual(['n']);
    expect(u.gain!).toBeGreaterThan(0.2);
    expect(u.fatKg! - 20).toBeLessThan(-0.5);
  });

  it('default 2.5/2.5: a new −3 kg change keeps its likelihood after 0, 10 or 50 unrelated consumed readings', () => {
    const g = [0, 10, 50].map((m) => afterHistory(m, -3));
    for (const u of g) {
      expect(u.status).toBe('updated');
      expect(u.gain!).toBeGreaterThan(0.1);
      expect(u.fatKg! - 20).toBeLessThan(-0.3);
      // the absolute bias variance never collapses
      expect(u.groups[0]!.biasSdPct).toBeGreaterThanOrEqual(floorPct(2.5) - 1e-9);
      expect(u.levelSdKg!).toBeGreaterThanOrEqual(Math.sqrt(1 / (1 / P + 1 / (S * S * 2.5 * 2.5))) - 1e-9);
    }
    expect(g[2]!.gain!).toBeGreaterThan(0.5 * g[0]!.gain!);
    expect(g[1]!.longitudinal).toEqual({ status: 'scenario', reasonCode: 'stableDeviceBiasAssumed' });
    expect(g[0]!.longitudinal).toBeUndefined();
  });

  it('a stable biased device over a changing fat mass (tissue unchanged): the path tracks the change, the bias floor holds', () => {
    const biasKg = 1.5 * S;
    const path: number[] = [20];
    const N = 20;
    for (let k = 1; k <= N; k++) {
      const D = 7 * k;
      const anchorDays = Array.from({ length: k - 1 }, (_, j) => 7 * (j + 1));
      // the path holds P_j from the anchor of decision j−1 up to the day before decision j
      const r = fakeReplay((d) => path[Math.min(path.length - 1, Math.floor(d / 7))]!, { anchorDays });
      const readings: CompositionReading[] = Array.from({ length: k }, (_, j) => ({ observationId: `r${j}`, day: 7 * (j + 1) - 1, method: 'bia', scanFatMassKg: 20 - 0.3 * j + biasKg, scanMassKg: 72, device: 'A' }));
      const u = fakeTarget(r, D, { readings }, { consumed: new Set(readings.slice(0, -1).map((x) => x.observationId!)), history: anchorDays.map((d, j) => ({ day: d, consumed: [`r${j}`] })) });
      expect(u.status).toBe('updated');
      expect(u.groups[0]!.biasSdPct).toBeGreaterThanOrEqual(floorPct(2.5) - 1e-9);
      path.push(u.fatKg!);
    }
    // the last ten decisions follow the true −0.3 kg/week within a bounded lag (BIA gain ≤ 0.3)
    const slope = (path[N]! - path[N - 10]!) / 10;
    expect(slope).toBeLessThan(-0.2);
    expect(slope).toBeGreaterThan(-0.4);
  });

  it('batch = sequential: the second decision equals the fixed-prior joint batch GLS of the same Gaussian model (no cap)', () => {
    const rep = 1;
    const sys = 1.5;
    const yA = 22;
    const yB = 21;
    const rd = (id: string, d: number, y: number): CompositionReading => ({ observationId: id, day: d, method: 'dxa', scanFatMassKg: y, scanMassKg: 72, device: 'S', repeatabilitySdPct: rep, systematicSdPct: sys });
    const r1 = fakeReplay(() => 20);
    const u1 = fakeTarget(r1, 14, { readings: [rd('A', 13, yA)] });
    const e1 = u1.fatKg! - 20;
    const r2 = fakeReplay((d) => (d >= 14 ? 20 + e1 : 20), { anchorDays: [14] });
    const u2 = fakeTarget(r2, 21, { readings: [rd('A', 13, yA), rd('B', 20, yB)] }, { consumed: new Set(['A']), history: [{ day: 14, consumed: ['A'] }] });
    const e2Seq = u2.fatKg! - (20 + e1);
    // batch: x = [e1, w, b]; ν_A = e1 + S·b + ε_A, ν_B(raw, vs the original path) = e1 + w + S·b + ε_B, target e2 = e1 + w
    const R = (S * rep) ** 2;
    const V1 = P - (P * P) / (P + S * S * sys * sys + R);
    const Q = P - V1;
    const prior = [P, Q, sys * sys];
    const H = [[1, 0, S], [1, 1, S]];
    const nu = [yA - 20, yB - 20];
    const Sm = H.map((hi) => H.map((hj) => hi.reduce((a, v, k) => a + v * prior[k]! * hj[k]!, 0)));
    Sm[0]![0]! += R;
    Sm[1]![1]! += R;
    const det = Sm[0]![0]! * Sm[1]![1]! - Sm[0]![1]! * Sm[1]![0]!;
    const inv = [[Sm[1]![1]! / det, -Sm[0]![1]! / det], [-Sm[1]![0]! / det, Sm[0]![0]! / det]];
    const c = [1, 1, 0]; // e2 = e1 + w
    const cov = H.map((hi) => hi.reduce((a, v, k) => a + c[k]! * prior[k]! * v, 0));
    const w = [cov[0]! * inv[0]![0]! + cov[1]! * inv[1]![0]!, cov[0]! * inv[0]![1]! + cov[1]! * inv[1]![1]!];
    const e2Batch = w[0]! * nu[0]! + w[1]! * nu[1]!;
    expect(e2Seq).toBeCloseTo(e2Batch - e1, 9);
    // within one decision, several fresh readings are the batch of their sequential updates (order does not matter)
    const fwd = fakeTarget(r1, 14, { readings: [rd('A', 10, 22), rd('B', 13, 21), rd('C', 12, 23)] });
    const rev = fakeTarget(r1, 14, { readings: [rd('C', 12, 23), rd('B', 13, 21), rd('A', 10, 22)] });
    expect(fwd.fatKg!).toBeCloseTo(rev.fatKg!, 12);
    // a retry of the same decision earns nothing
    const retry = fakeTarget(r2, 21, { readings: [rd('A', 13, yA), rd('B', 20, yB)] }, { consumed: new Set(['A', 'B']), history: [{ day: 14, consumed: ['A'] }, { day: 21, consumed: ['B'] }] });
    expect(retry.status).toBe('noNewReadings');
  });

  it('a method or device change opens a new segment without change information', () => {
    const days = [7, 14];
    const r = fakeReplay(() => 20, { anchorDays: days });
    const prior: CompositionReading[] = days.map((d, k) => ({ observationId: `p${k}`, day: d - 1, method: 'bia', scanFatMassKg: 20, scanMassKg: 72, device: 'A' }));
    const opts = { consumed: new Set(['p0', 'p1']), history: days.map((d, k) => ({ day: d, consumed: [`p${k}`] })) };
    const dxa = fakeTarget(r, 21, { readings: [...prior, { observationId: 'x', day: 20, method: 'dxa', scanFatMassKg: 19, scanMassKg: 72 }] }, opts);
    expect(dxa.groups[0]).toMatchObject({ groupId: 'dxa:unknownDevice', priorDecisions: 0, changeInformation: false, bias: 'unknownDevice' });
    expect(dxa.longitudinal).toBeUndefined();
    const other = fakeTarget(r, 21, { readings: [...prior, { observationId: 'y', day: 20, method: 'bia', scanFatMassKg: 19, scanMassKg: 72, device: 'B' }] }, opts);
    expect(other.groups[0]).toMatchObject({ groupId: 'bia:B', changeInformation: false });
    expect(other.gain!).toBeLessThanOrEqual(0.3 + 1e-12);
  });
});

