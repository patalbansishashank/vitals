/** A replay stub with a piecewise fat path, constant tissue/water, and the anchor days the path absorbed. */
function fakeReplay(fat: (d: number) => number, opts: { days?: number; tissue?: number; water?: number; anchorDays?: number[] } = {}): ReplayOutput {
  const n = opts.days ?? 400;
  const tissue = opts.tissue ?? 70;
  const water = opts.water ?? 2;
  return {
    startDay: 0,
    fatKg: Float64Array.from({ length: n }, (_, d) => fat(d)),
    tissueWakeKg: new Float64Array(n).fill(tissue),
    waterWakeKg: new Float64Array(n).fill(water),
    anchorsApplied: (opts.anchorDays ?? []).map((day) => ({ day, tissueBeforeKg: tissue, tissueAfterKg: tissue, dFatKg: 0, dLeanKg: 0, leanShare: 0, storedEnergyKcal: 0 })),
    waterHourKg: null,
    result: { daily: {} },
  } as unknown as ReplayOutput;
}
